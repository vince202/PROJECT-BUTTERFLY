/**
 * Shared helpers for the i18n scripts: load a French catalogue, flatten its
 * messages to plain text with `{param}` placeholders, and write an English
 * catalogue file in the same shape.
 */
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import type { Namespace } from '../src/i18n';

export interface FlatMessage {
  key: string;
  /** French text with {param} placeholders (functions rendered with a proxy). */
  text: string;
  params: string[];
  /** The function body contained logic (ternary, plural…): review the translation by hand. */
  review: boolean;
}

/** Render a message function with a proxy that yields `{param}` markers. */
export function flatten(ns: string, messages: Namespace, sources: Record<string, string> = {}): FlatMessage[] {
  const out: FlatMessage[] = [];
  for (const [id, msg] of Object.entries(messages)) {
    if (typeof msg === 'string') {
      out.push({ key: `${ns}.${id}`, text: msg, params: [], review: false });
      continue;
    }
    const used = new Set<string>();
    const proxy = new Proxy({} as Record<string, string>, {
      get: (_t, k) => {
        if (typeof k !== 'string') return undefined;
        used.add(k);
        return `{${k}}`;
      },
    });
    let text: string;
    try {
      text = String(msg(proxy as never));
    } catch {
      text = `[[erreur de rendu: ${id}]]`;
    }
    const src = sources[id] ?? msg.toString();
    const review = /\?|plural\(|Number\(|>\s*1|===|!==/.test(src) || /\[\[erreur/.test(text);
    out.push({ key: `${ns}.${id}`, text, params: [...used], review });
  }
  return out;
}

/** Load `src/i18n/<locale>/index.ts` through tsx and return its namespaces. */
export async function loadCatalogue(locale: 'fr' | 'en'): Promise<Record<string, Namespace>> {
  const url = pathToFileURL(`${process.cwd()}/src/i18n/${locale}/index.ts`).href;
  const mod = (await import(url)) as Record<string, Namespace>;
  const out: Record<string, Namespace> = {};
  for (const [k, v] of Object.entries(mod)) if (v && typeof v === 'object') out[k] = v;
  return out;
}

/** Best-effort extraction of each key's source text from a catalogue file (for review flags). */
export function sourceSnippets(file: string): Record<string, string> {
  const out: Record<string, string> = {};
  let text = '';
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    return out;
  }
  const re = /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z0-9_]+))\s*:\s*([\s\S]*?)(?=,\n\s*(?:'[^']+'|"[^"]+"|[A-Za-z0-9_]+)\s*:|\n\};)/gm;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) out[m[1] ?? m[2] ?? m[3]] = m[4];
  return out;
}

function tsString(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
}

function tsTemplate(s: string): string {
  return '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${').replace(/\{([A-Za-z0-9_]+)\}/g, '${$1}') + '`';
}

/** Build the TypeScript source of an English namespace file from translated flat messages. */
export function renderNamespaceFile(ns: string, messages: { id: string; text: string; params: string[]; review: boolean }[]): string {
  const lines: string[] = [];
  lines.push("import type { Namespace } from '../index';", '', `/** English catalogue for \`${ns}\` — generated by scripts/i18n-translate.ts, then reviewed by hand. */`, `export const ${ns}: Namespace = {`);
  for (const m of messages) {
    const id = /^[A-Za-z_][A-Za-z0-9_]*$/.test(m.id) ? m.id : tsString(m.id);
    const review = m.review ? ' // REVIEW: the French message had logic (plural/ternary); check this translation' : '';
    if (!m.params.length) lines.push(`  ${id}: ${tsString(m.text)},${review}`);
    else lines.push(`  ${id}: ({ ${m.params.join(', ')} }) => ${tsTemplate(m.text)},${review}`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

