import { Reality } from '../src/sim/reality';
import { compareRealities } from '../src/sim/compare';
import { busDelayFor } from '../src/sim/interventions';
import { fmtTime } from '../src/sim/time';
const seed = Number(process.argv[2] ?? 29);
const at = process.argv[3] ?? '08:20';
const [h, m] = at.split(':').map(Number);
const A = new Reality({ id: 'A', name: 'A', seed, interventions: [] }).generate();
const arr = A.events.find((e) => e.type === 'bus_arrive' && e.t === h * 60 + m)!;
const B = new Reality({ id: 'B', name: 'B', seed, interventions: [busDelayFor(arr, 3)] }).generate();
const c = compareRealities(A, B);
console.log(c.summary.join('\n'));
console.log('\n-- consequences (B, verified) --');
for (const x of c.consequences) console.log(`${fmtTime(x.b!.t)} [${x.status}${x.dt ? ` ${x.dt > 0 ? '+' : ''}${x.dt}` : ''}] ${x.b!.label}`);
console.log('\n-- only A (non-noise) --');
for (const x of c.onlyA) console.log(`${fmtTime(x.a!.t)} [${x.causal}] ${x.a!.label}`);
console.log('\n-- only B (non-noise) --');
for (const x of c.onlyB) console.log(`${fmtTime(x.b!.t)} [${x.causal}] ${x.b!.label}`);
console.log('\n-- shifted (non-noise) --');
for (const x of c.shifted.slice(0, 40)) console.log(`${fmtTime(x.a!.t)}→${fmtTime(x.b!.t)} [${x.causal}] ${x.b!.label}`);
